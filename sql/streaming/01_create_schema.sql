CREATE SCHEMA IF NOT EXISTS streaming;

CREATE TABLE IF NOT EXISTS streaming.raw_events (
    raw_event_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          VARCHAR(255),
    kafka_topic       VARCHAR(255) NOT NULL,
    kafka_key         VARCHAR(255),
    kafka_partition   INTEGER NOT NULL,
    kafka_offset      BIGINT NOT NULL,
    kafka_timestamp   TIMESTAMPTZ,
    raw_payload       TEXT NOT NULL,
    parsed_payload    JSONB,
    processing_status VARCHAR(20) NOT NULL DEFAULT 'received'
        CHECK (processing_status IN ('received', 'processed', 'rejected')),
    error_message     TEXT,
    received_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at      TIMESTAMPTZ,
    CONSTRAINT uq_raw_events_kafka
        UNIQUE (kafka_topic, kafka_partition, kafka_offset)
);

CREATE TABLE IF NOT EXISTS streaming.fact_weather_daily (
    sk_weather_event  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_event_id      BIGINT NOT NULL UNIQUE
        REFERENCES streaming.raw_events(raw_event_id),
    event_id          VARCHAR(255) NOT NULL UNIQUE,
    simulation_id     VARCHAR(64) NOT NULL,
    sk_geografia      INTEGER NOT NULL
        REFERENCES comun.dim_geografia(sk_geografia),
    sk_fecha          INTEGER NOT NULL
        REFERENCES weather.dim_fecha(sk_fecha),
    is_simulated      BOOLEAN NOT NULL,
    temperature_mean  NUMERIC(10, 2),
    temperature_max   NUMERIC(10, 2),
    temperature_min   NUMERIC(10, 2),
    precipitation_mm  NUMERIC(10, 2),
    relative_humidity NUMERIC(10, 2),
    et0_mm            NUMERIC(10, 2),
    published_at      TIMESTAMPTZ NOT NULL,
    loaded_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_stream_fact_simulation
    ON streaming.fact_weather_daily (simulation_id);
CREATE INDEX IF NOT EXISTS ix_stream_fact_geografia
    ON streaming.fact_weather_daily (sk_geografia);
CREATE INDEX IF NOT EXISTS ix_stream_fact_fecha
    ON streaming.fact_weather_daily (sk_fecha);